async function seed() {
  console.log(`Starting to seed ${COUNTRIES_RAW.length} countries into country_codes table...`);
  
  // Truncate / clear existing rows to ensure clean start
  await pool.query('TRUNCATE TABLE country_codes');

  let inserted = 0;
  for (const c of COUNTRIES_RAW) {
    const flag = getFlagEmoji(c.iso);
    const isDef = c.isDefault || 0;
    const sort = c.sortOrder || 100;
    const minLen = c.minLen || 7;
    const maxLen = c.maxLen || 15;
    const phoneLen = c.phoneLen || 10;

    await pool.query(`
      INSERT INTO country_codes (country_name, country_code, iso_code, phone_length, min_length, max_length, flag_emoji, is_default, sort_order)
      VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
    `, [c.name, c.code, c.iso, phoneLen, minLen, maxLen, flag, isDef, sort]);
    inserted++;
  }

  const [[res]] = await pool.query('SELECT COUNT(*) as cnt FROM country_codes');
  console.log(`Successfully seeded! Total records in country_codes table: ${res.cnt}`);
  
  // Show first 10 rows
  const [samples] = await pool.query('SELECT id, country_name, country_code, iso_code, phone_length, min_length, max_length, flag_emoji, is_default, sort_order FROM country_codes ORDER BY sort_order ASC, country_name ASC LIMIT 20');
  console.log('Sample rows:');
  console.table(samples);

  process.exit(0);
}

seed().catch(err => {
  console.error('Seeding failed:', err);
  process.exit(1);
});
