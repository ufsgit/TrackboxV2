const { default: makeWASocket, DisconnectReason, fetchLatestBaileysVersion } = require('@whiskeysockets/baileys');
const pino = require('pino');
const pool = require('../../db/pool');
const { useMySQLAuthState } = require('./authState.service');
const { generateQrDataUrl } = require('../../utils/whatsapp/qrImageHelper');
const { getPhoneVariants } = require('../../utils/whatsapp/phoneNormalizer');
const { assignIncomingMessage } = require('./messageAssignment.service');
const { saveOrUpdateSession, disconnectSession } = require('../../models/whatsapp/WhatsappQrSession');

// In-memory active sockets store: Map<sessionId, socketInstance>
const activeSockets = new Map();
// In-memory pending verification data: Map<sessionId, { user, phoneNumber, businessId }>
const pendingVerifications = new Map();
// Sessions that have been rejected (e.g. user does not exist) to prevent auto-reconnect loops
const rejectedSessions = new Set();
// Cache mapping LID to real phone JID: Map<lidClean, phoneJidClean>
const lidPhoneMap = new Map();

/**
 * Initializes or restarts a Baileys WhatsApp WebSocket instance
 */
async function startBaileysSession(sessionId, io) {
  // If this session was previously rejected, do not start or reconnect
  if (rejectedSessions.has(sessionId)) {
    console.log(`[Baileys Session] Skipping start: Session ${sessionId} was rejected.`);
    return null;
  }

  if (activeSockets.has(sessionId)) {
    console.log(`[Baileys Session] Socket already active for session: ${sessionId}`);
    return activeSockets.get(sessionId);
  }

  const { state, saveCreds } = await useMySQLAuthState(sessionId);
  const { version } = await fetchLatestBaileysVersion().catch(() => ({ version: [2, 3000, 1015901307] }));

  const sock = makeWASocket({
    version,
    logger: pino({ level: 'silent' }),
    auth: state,
    printQRInTerminal: false,
    browser: ['Trackbox CRM', 'Chrome', '124.0.0.0'],
    syncFullHistory: false
  });

  activeSockets.set(sessionId, sock);

  sock.ev.on('creds.update', saveCreds);

  // Sync and cache contacts (LID to phone number mapping)
  sock.ev.on('contacts.upsert', (contacts) => {
    for (const c of contacts) {
      if (c.id && c.lid) {
        const cleanLid = c.lid.split('@')[0];
        const cleanPhone = c.id.split('@')[0];
        lidPhoneMap.set(cleanLid, cleanPhone);
      }
    }
  });

  sock.ev.on('contacts.update', (updates) => {
    for (const u of updates) {
      if (u.id && u.lid) {
        const cleanLid = u.lid.split('@')[0];
        const cleanPhone = u.id.split('@')[0];
        lidPhoneMap.set(cleanLid, cleanPhone);
      }
    }
  });

  // Connection Lifecycle
  sock.ev.on('connection.update', async (update) => {
    const { connection, lastDisconnect, qr } = update;

    // 1. QR Code generated by WhatsApp
    if (qr) {
      try {
        const qrImage = await generateQrDataUrl(qr);
        io.to(`session_${sessionId}`).emit('whatsapp_qr_code', {
          sessionId,
          qrImage
        });
      } catch (err) {
        console.error('[Baileys Session] Failed to generate QR data URL:', err);
      }
    }

    // 2. Connection state transitions
    if (connection === 'open') {
      console.log(`[Baileys Session] Connection OPEN for session ${sessionId}`);

      // Extract phone number from JID (e.g. 919876543210:1@s.whatsapp.net -> 919876543210)
      const rawJid = sock.user?.id || '';
      const rawPhone = rawJid.split(':')[0].replace(/@.+/, '');

      console.log(`[Baileys Session] Scanned phone number detected: ${rawPhone}`);

      // Check against users table (matches 10-digit phone number)
      const phoneVariants = getPhoneVariants(rawPhone);
      let matchedUser = null;

      if (phoneVariants.length > 0) {
        const placeholders = phoneVariants.map(() => '?').join(',');
        const [rows] = await pool.query(
          `SELECT id, name, email, phone, role, business_id, is_active, username, employee_code 
           FROM users 
           WHERE (phone IN (${placeholders}) OR RIGHT(phone, 10) IN (${placeholders}))
           LIMIT 1`,
          [...phoneVariants, ...phoneVariants]
        );

        if (rows.length > 0) {
          matchedUser = rows[0];
        }
      }

      // If user does not exist in users table
      if (!matchedUser) {
        console.warn(`[Baileys Session] No user found with phone: ${rawPhone}. Rejecting and logging out.`);
        rejectedSessions.add(sessionId);

        // Emit error to frontend immediately
        io.to(`session_${sessionId}`).emit('whatsapp_verify_result', {
          success: false,
          message: 'User with this number does not exist',
          phoneNumber: rawPhone
        });

        // Small delay to allow WhatsApp's WebSocket handshake to stabilize,
        // ensuring the logout packet is successfully delivered to the phone to revoke the session
        setTimeout(async () => {
          try {
            console.log(`[Baileys Session] Sending explicit logout to WhatsApp for ${sessionId}...`);
            await sock.logout('User does not exist');
          } catch (e) {
            console.warn(`[Baileys Session] Logout error for ${sessionId}:`, e.message);
          } finally {
            cleanupSession(sessionId);
            await disconnectSession(sessionId);
            // Delete DB auth tokens completely so no leftover credentials persist
            await pool.query('DELETE FROM whatsapp_qr_sessions WHERE session_id = ?', [sessionId]).catch(() => {});
          }
        }, 600);

        return;
      }

      // If user exists: store pending verification and prompt frontend for confirmation
      pendingVerifications.set(sessionId, {
        user: matchedUser,
        phoneNumber: rawPhone,
        businessId: matchedUser.business_id
      });

      io.to(`session_${sessionId}`).emit('whatsapp_verify_result', {
        success: true,
        message: 'Staff user identified. Confirmation required.',
        phoneNumber: rawPhone,
        user: {
          id: matchedUser.id,
          name: matchedUser.name,
          email: matchedUser.email,
          phone: matchedUser.phone || rawPhone,
          role: matchedUser.role,
          employeeCode: matchedUser.employee_code
        }
      });
    }

    if (connection === 'close') {
      const statusCode = (lastDisconnect?.error)?.output?.statusCode;
      const isLoggedOut = statusCode === DisconnectReason.loggedOut || statusCode === 401;
      const isTimedOut = statusCode === DisconnectReason.connectionTimedOut || statusCode === 408;
      const isRestartRequired = statusCode === DisconnectReason.restartRequired || statusCode === 515;
      const isRejected = rejectedSessions.has(sessionId);

      cleanupSession(sessionId);

      // Check if this session was officially confirmed and active in DB
      const [dbRows] = await pool.query(
        'SELECT status, is_active FROM whatsapp_qr_sessions WHERE session_id = ? LIMIT 1',
        [sessionId]
      ).catch(() => [[]]);
      const isDbConnected = dbRows.length > 0 && dbRows[0].status === 'connected' && dbRows[0].is_active === 1;

      // Only reconnect if:
      // 1. It is a 515 restartRequired during active pairing
      // 2. OR it is an already confirmed, connected session in MySQL suffering a temporary network blip
      // NEVER reconnect for timed out QR codes (408), logged out (401), or rejected sessions
      const shouldReconnect = !isLoggedOut && !isTimedOut && !isRejected && (isRestartRequired || isDbConnected);

      console.log(`[Baileys Session] Connection closed for ${sessionId}. Status code: ${statusCode}. Reconnecting: ${shouldReconnect}`);

      if (isLoggedOut || isRejected || isTimedOut) {
        // If logged out from phone (401) or rejected: permanently delete session from DB
        if (isLoggedOut || isRejected) {
          console.log(`[Baileys Session] Device logged out or rejected. Deleting session from DB: ${sessionId}`);
          await pool.query('DELETE FROM whatsapp_qr_sessions WHERE session_id = ?', [sessionId]).catch(() => {});
        } else if (!isDbConnected) {
          await disconnectSession(sessionId);
        }

        io.to(`session_${sessionId}`).emit('whatsapp_status_update', {
          sessionId,
          status: 'disconnected'
        });
      } else if (shouldReconnect) {
        console.log(`[Baileys Session] Reconnecting session ${sessionId} in 500ms...`);
        setTimeout(() => {
          startBaileysSession(sessionId, io).catch((err) => {
            console.error(`[Baileys Session] Error during auto-reconnect for ${sessionId}:`, err);
          });
        }, 500);
      }
    }
  });

  // Handle Inbound Messages
  sock.ev.on('messages.upsert', async ({ messages, type }) => {
    if (type !== 'notify') return;

    // Check DB: Messages must ONLY be processed if this session has been confirmed & active in MySQL
    const [confirmedSessionRows] = await pool.query(
      'SELECT user_id, business_id, status, is_active FROM whatsapp_qr_sessions WHERE session_id = ? LIMIT 1',
      [sessionId]
    ).catch(() => [[]]);

    if (confirmedSessionRows.length === 0 || confirmedSessionRows[0].status !== 'connected' || confirmedSessionRows[0].is_active !== 1) {
      // Session has NOT been confirmed yet by the user on the UI, or was deleted from MySQL
      return;
    }

    const { user_id: userId, business_id: businessId } = confirmedSessionRows[0];

    for (const msg of messages) {
      if (!msg.message || msg.key.fromMe) continue;

      // Check all possible places Baileys provides the real phone number
      const remoteJid = msg.key?.remoteJid || '';
      const participant = msg.key?.participant || msg.participant || '';
      const remoteJidAlt = msg.key?.remoteJidAlt || '';
      const participantPn = msg.key?.participantPn || msg.key?.senderPn || '';

      let senderJid = '';

      // 1. Check direct phone fields first
      if (participantPn && participantPn.includes('@s.whatsapp.net')) {
        senderJid = participantPn;
      } else if (remoteJidAlt && remoteJidAlt.includes('@s.whatsapp.net')) {
        senderJid = remoteJidAlt;
      } else if (remoteJid && remoteJid.includes('@s.whatsapp.net')) {
        senderJid = remoteJid;
      } else if (participant && participant.includes('@s.whatsapp.net')) {
        senderJid = participant;
      }

      // 2. If it is an @lid, check our contacts cache map
      if (!senderJid || senderJid.includes('@lid')) {
        const targetLid = (remoteJid.includes('@lid') ? remoteJid : participant).split('@')[0];
        if (lidPhoneMap.has(targetLid)) {
          senderJid = `${lidPhoneMap.get(targetLid)}@s.whatsapp.net`;
        }
      }

      // 3. Fallback to signalRepository if available
      if (!senderJid || senderJid.includes('@lid')) {
        try {
          const resolved = await sock?.signalRepository?.lidToJid?.(remoteJid);
          if (resolved && resolved.includes('@s.whatsapp.net')) {
            senderJid = resolved;
          }
        } catch (e) {}
      }

      // Fallback to whatever JID exists if still unresolved
      if (!senderJid) {
        senderJid = remoteJid || participant;
      }

      // Skip group chats or broadcast status updates
      if (senderJid.endsWith('@g.us') || senderJid.includes('broadcast')) continue;

      const text = msg.message?.conversation ||
                   msg.message?.extendedTextMessage?.text ||
                   msg.message?.imageMessage?.caption || '';

      await assignIncomingMessage({
        sessionId,
        userId,
        businessId,
        messageData: {
          from: senderJid,
          text,
          pushName: msg.pushName,
          timestamp: msg.messageTimestamp ? msg.messageTimestamp * 1000 : Date.now(),
          messageId: msg.key?.id
        }
      });
    }
  });

  return sock;
}

/**
 * Confirms assignment of the WhatsApp session to the verified user
 */
async function confirmSessionAssignment(sessionId, userId) {
  const pending = pendingVerifications.get(sessionId);
  if (!pending) {
    throw new Error('No pending verified session found to confirm');
  }

  if (String(pending.user.id) !== String(userId)) {
    throw new Error('User ID does not match the verified phone session');
  }

  // 1. If this user had a prior active session, cleanly close that older socket
  const [existingUserSessions] = await pool.query(
    'SELECT session_id FROM whatsapp_qr_sessions WHERE user_id = ? AND session_id != ?',
    [userId, sessionId]
  );
  for (const s of existingUserSessions) {
    cleanupSession(s.session_id);
    await disconnectSession(s.session_id);
  }

  // 2. Update DB session record (1 unique session per user)
  await saveOrUpdateSession({
    sessionId,
    userId: pending.user.id,
    businessId: pending.businessId,
    phoneNumber: pending.phoneNumber,
    status: 'connected',
    isActive: 1
  });

  return {
    success: true,
    message: `WhatsApp session successfully assigned to ${pending.user.name}`,
    user: pending.user,
    phoneNumber: pending.phoneNumber
  };
}

/**
 * Cleans up active socket connection from memory
 */
function cleanupSession(sessionId) {
  if (activeSockets.has(sessionId)) {
    const s = activeSockets.get(sessionId);
    try { s.end?.(); } catch (e) {}
    activeSockets.delete(sessionId);
  }
}

/**
 * Explicit disconnect requested by user/admin from the web app
 * Sends logout to phone so WhatsApp unlinks it, then deletes from DB.
 */
async function disconnectUserSession(sessionId) {
  rejectedSessions.delete(sessionId);
  pendingVerifications.delete(sessionId);

  // 1. If socket is active, send logout to WhatsApp so phone unlinks immediately
  if (activeSockets.has(sessionId)) {
    const s = activeSockets.get(sessionId);
    try {
      console.log(`[Baileys Session] Sending logout stanza to phone for session: ${sessionId}`);
      await s.logout('Disconnected from Trackbox');
    } catch (e) {
      console.warn(`[Baileys Session] Logout notice failed (socket may already be closed):`, e.message);
    }
  }

  // 2. Clean up socket from memory
  cleanupSession(sessionId);

  // 3. Permanently delete session row from database
  await pool.query('DELETE FROM whatsapp_qr_sessions WHERE session_id = ?', [sessionId]).catch(() => {});
}

function clearRejectedSession(sessionId) {
  rejectedSessions.delete(sessionId);
}

/**
 * Automatically resumes all active connected WhatsApp sessions upon server startup
 */
async function autoResumeActiveSessions(io) {
  try {
    const [activeSessions] = await pool.query(
      `SELECT session_id, user_id, phone_number 
       FROM whatsapp_qr_sessions 
       WHERE status = 'connected' AND is_active = 1`
    );

    if (activeSessions.length === 0) {
      console.log('[Baileys AutoResume] No active WhatsApp sessions to resume.');
      return;
    }

    console.log(`[Baileys AutoResume] Resuming ${activeSessions.length} active WhatsApp session(s)...`);

    for (const session of activeSessions) {
      console.log(`[Baileys AutoResume] Resuming session: ${session.session_id} (User: ${session.user_id}, Phone: ${session.phone_number})`);
      startBaileysSession(session.session_id, io).catch((err) => {
        console.error(`[Baileys AutoResume] Failed to resume session ${session.session_id}:`, err.message);
      });
    }
  } catch (err) {
    console.error('[Baileys AutoResume] Error loading active sessions on startup:', err.message);
  }
}

module.exports = {
  startBaileysSession,
  confirmSessionAssignment,
  disconnectUserSession,
  clearRejectedSession,
  autoResumeActiveSessions,
  activeSockets,
  pendingVerifications
};

